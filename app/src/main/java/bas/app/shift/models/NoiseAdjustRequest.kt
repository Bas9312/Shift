package bas.app.shift.models

data class NoiseAdjustRequest(
    /**
     * Сколько шума начислить. Для команд из справочника цену ставит сервер и это поле
     * игнорируется — присылаем его только там, где значение задаёт мастер
     * (DEEP_DIVE.END: шум равен глубине погружения).
     */
    val delta: Double,
    /**
     * Просим сервер самому разделить прирост на узел Proxy и партнёра по Cross-Link.
     * Раньше это делал клиент, но шум начисляется ещё и с сайта, где клиента нет —
     * поэтому деление переехало на сервер, в noize_api/service.php.
     * Флаг нужен для совместимости: без него сервер ведёт себя по-старому и не делит,
     * так что версии приложения, которые делят сами, продолжают работать как раньше.
     */
    val split: Boolean = true,
    /**
     * Имя команды терминала. Сервер по нему берёт цену из своего справочника, чтобы
     * баланс правился из панели мастера, а не пересборкой приложения. Команда неизвестна
     * серверу (или её нет) — начисляется `delta`, как раньше.
     */
    val command: String? = null
)
